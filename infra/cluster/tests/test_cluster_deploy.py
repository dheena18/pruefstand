"""T3.1a CPU tests: ``infra/gpu/deploy-cluster-bin.sh`` (copy over SSH, ``*.partial`` + ``mv``, SHA256SUMS)."""

import getpass
import hashlib
from pathlib import Path

import pytest
from gpu_testkit import CLUSTER_DIR, GPU_DIR, fake_ssh, link_tools, run_script
from vm_testkit import Result, Stubs

DEPLOY = GPU_DIR / "deploy-cluster-bin.sh"


@pytest.fixture
def remote(tmp_path: Path, stubs: Stubs) -> Path:
    root = tmp_path / "remote"
    root.mkdir()
    fake_ssh(stubs, root)
    link_tools(stubs)
    return root


def _deploy(stubs: Stubs, *args: str, user: str | None = None, **env: str) -> Result:
    env = {
        "PRUEFSTAND_SERVICE_USER": user or getpass.getuser(),
        "CLUSTER_SSH_HOST": "cairo-s101lp",
        **env,
    }
    return run_script(DEPLOY, *args, stubs=stubs, env=env)


def test_deploy_copies_scripts_env_and_sums_over_ssh(stubs: Stubs, remote: Path) -> None:
    res = _deploy(stubs)
    assert res.rc == 0, res.err
    target = remote / "pruefstand-bin"
    names = {p.name for p in target.iterdir()}
    expected = {p.name for p in CLUSTER_DIR.glob("*.sh")} | {"cluster.env", "SHA256SUMS"}
    assert names == expected
    assert not list(target.glob("*.partial"))
    sums = (target / "SHA256SUMS").read_text().splitlines()
    assert any(line.endswith("  cluster.env") for line in sums)
    for line in sums:
        digest, name = line.split("  ", 1)
        assert hashlib.sha256((target / name).read_bytes()).hexdigest() == digest
    assert all("/data/dheena/pruefstand-bin" in c for c in stubs.calls("ssh"))


def test_rendered_cluster_env_comes_from_the_template(stubs: Stubs, remote: Path) -> None:
    _deploy(stubs)
    text = (remote / "pruefstand-bin" / "cluster.env").read_text()
    template = (CLUSTER_DIR / "cluster.env.template").read_text()
    body = [ln for ln in template.splitlines() if ln and not ln.startswith("#")]
    for line in body:
        assert line in text.splitlines()
    assert text.startswith("# generated by deploy-cluster-bin.sh")


def test_a_non_service_user_writes_the_dev_dir(stubs: Stubs, remote: Path) -> None:
    res = _deploy(stubs, user="someone-else")
    assert res.rc == 0, res.err
    assert (remote / "pruefstand-bin-dev" / "SHA256SUMS").is_file()
    assert not (remote / "pruefstand-bin").exists()


def test_bin_dev_flag_writes_the_dev_dir_for_the_service_user(stubs: Stubs, remote: Path) -> None:
    assert _deploy(stubs, "--bin-dev").rc == 0
    assert (remote / "pruefstand-bin-dev" / "SHA256SUMS").is_file()


def test_check_passes_after_deploy_and_detects_an_edit(
    stubs: Stubs, remote: Path, tmp_path: Path
) -> None:
    assert _deploy(stubs, "--check").rc != 0  # nothing deployed yet
    assert _deploy(stubs).rc == 0
    assert _deploy(stubs, "--check").rc == 0
    edited = tmp_path / "edited.template"
    edited.write_text((CLUSTER_DIR / "cluster.env.template").read_text() + "OLLAMA_EXTRA=1\n")
    res = _deploy(stubs, "--check", CLUSTER_ENV_TEMPLATE=str(edited))
    assert res.rc != 0
    assert "out of date" in res.err + res.out


def test_check_writes_nothing(stubs: Stubs, remote: Path) -> None:
    _deploy(stubs, "--check")
    assert not list(remote.rglob("*"))


def test_print_sums_needs_no_ssh(stubs: Stubs) -> None:
    res = _deploy(stubs, "--print-sums")
    assert res.rc == 0
    assert "cluster.env" in res.out
    assert not stubs.calls("ssh")


def test_a_template_line_with_shell_syntax_is_refused_before_any_copy(
    stubs: Stubs, remote: Path, tmp_path: Path
) -> None:
    bad = tmp_path / "bad.template"
    bad.write_text("OLLAMA_HOST=127.0.0.1:11434; touch /tmp/pwn\n")
    res = _deploy(stubs, CLUSTER_ENV_TEMPLATE=str(bad))
    assert res.rc == 1
    assert not list(remote.rglob("*"))


def test_unknown_argument_is_a_usage_error(stubs: Stubs, remote: Path) -> None:
    del remote
    assert _deploy(stubs, "--force").rc == 64


def test_deploy_needs_no_gpu_lock(stubs: Stubs, remote: Path) -> None:
    del remote
    res = _deploy(stubs, "--print-sums", PRUEFSTAND_LOCK_HELD="")
    assert res.rc == 0
