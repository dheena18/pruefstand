#!/usr/bin/env bash
# install-cluster-wrapper.sh [--replace] [--print-sudoers]: install pruefstand-cluster and its sudoers line (OWNER step, sudo).
#
#   make gpu-install-wrapper        (exports origin/main with `git archive`, then runs this script with sudo)
#   sudo infra/gpu/install-cluster-wrapper.sh   (from a checkout: it then insists on a tree equal to origin/main)
#
# Installs infra/gpu/pruefstand-cluster to /usr/local/bin/pruefstand-cluster (root:root 0755), the allow-list
# /usr/local/lib/pruefstand-cluster.allow (generated here from models.yaml: "tag<TAB>bytes", the only tags and sizes the
# wrapper accepts) and ONE sudoers file, /etc/sudoers.d/pruefstand-cluster (0440), checked with `visudo -c -f` BEFORE it is
# moved into place. The sudoers file lets group pruefstand run exactly that one wrapper as user pruefstand and keeps
# PRUEFSTAND_LOCK_HELD through sudo. Confused-deputy guards (M3): lib/git_verify.sh refuses an unreviewed working tree;
# an existing file at one of the three targets that this installer did not create (no marker) is never overwritten
# unless --replace is given, and then a diff is printed first. The installer prints the commit it installed.
# These checks are a GUARDRAIL against accidental or unreviewed local edits, not a security boundary: the owner account
# is in group docker (root-equivalent) and agents run as that account, so a hostile agent could bypass any check that
# lives in the owner's tree. The real protection is that the owner installs from a checkout agents did not touch, which
# the make target guarantees by exporting the fetched main instead of the working tree.
# --print-sudoers prints the sudoers file and changes nothing. DESTDIR (a test seam) installs below that directory
# without root. Exit: 0 ok, 1 refused (tree, foreign file, visudo), 2 not run with sudo, 64 usage.
set -euo pipefail

GPU_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$GPU_DIR/../.." && pwd)"
WRAPPER_MARK="installed-by: infra/gpu/install-cluster-wrapper.sh"
SUDOERS_MARK="installed by infra/gpu/install-cluster-wrapper.sh"
ALLOW_MARK="# generated by install-cluster-wrapper.sh"

sudoers() {
  cat <<'FRAGMENT'
# /etc/sudoers.d/pruefstand-cluster (T3.1a, installed by infra/gpu/install-cluster-wrapper.sh)
# Group pruefstand (the owner login user is a member) may run ONE wrapper as user pruefstand, the only holder of
# the cluster key. The wrapper accepts fixed ops and listed tags only and checks that the GPU lock is held for the mutating ones.
Defaults!/usr/local/bin/pruefstand-cluster env_keep += "PRUEFSTAND_LOCK_HELD"
%pruefstand ALL=(pruefstand) NOPASSWD: /usr/local/bin/pruefstand-cluster
FRAGMENT
}

replace=0
for arg in "$@"; do
  case "$arg" in
    --print-sudoers)
      sudoers
      exit 0
      ;;
    --replace) replace=1 ;;
    *)
      echo "usage: install-cluster-wrapper.sh [--replace] [--print-sudoers]" >&2
      exit 64
      ;;
  esac
done
dest="${DESTDIR:-}"
if [ -z "$dest" ] && [ "$(id -u)" -ne 0 ]; then
  echo "install-cluster-wrapper.sh: run it with sudo (it writes /usr/local/bin and /etc/sudoers.d)" >&2
  exit 2
fi
# shellcheck source=lib/git_verify.sh
. "$GPU_DIR/lib/git_verify.sh"
verify_reviewed_tree "$REPO"
commit="$(git -c "safe.directory=$REPO" -C "$REPO" rev-parse HEAD 2>/dev/null || cat "$REPO/COMMIT" 2>/dev/null || echo unknown)"

stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT
{
  echo "$ALLOW_MARK"
  "${PRUEFSTAND_PYTHON:-python3}" "$GPU_DIR/gpu_catalogue.py" allowlist
} >"$stage/allow"
sudoers >"$stage/sudoers"
if ! visudo -c -f "$stage/sudoers"; then
  echo "install-cluster-wrapper.sh: visudo refused the sudoers file; nothing installed" >&2
  exit 1
fi

wrapper_dst="$dest/usr/local/bin/pruefstand-cluster"
allow_dst="$dest/usr/local/lib/pruefstand-cluster.allow"
sudoers_dst="$dest/etc/sudoers.d/pruefstand-cluster"
changed=0
check_target() { # source target marker-text
  local src="$1" dst="$2" mark="$3"
  if ! [ -e "$dst" ]; then
    changed=1
    return 0
  fi
  if cmp -s "$src" "$dst"; then return 0; fi
  if ! grep -qF "$mark" "$dst" && [ "$replace" -ne 1 ]; then
    echo "install-cluster-wrapper.sh: $dst exists and was not created by this installer; check it, then use --replace" >&2
    return 1
  fi
  echo "--- changes to $dst"
  diff -u "$dst" "$src" || true
  changed=1
}
ok=0
check_target "$GPU_DIR/pruefstand-cluster" "$wrapper_dst" "$WRAPPER_MARK" || ok=1
check_target "$stage/allow" "$allow_dst" "$ALLOW_MARK" || ok=1
check_target "$stage/sudoers" "$sudoers_dst" "$SUDOERS_MARK" || ok=1
if [ "$ok" -ne 0 ]; then exit 1; fi
if [ "$changed" -eq 0 ]; then
  echo "already installed (commit $commit)"
  exit 0
fi

owner=()
if [ -z "$dest" ]; then owner=(-o root -g root); fi
mkdir -p "$dest/usr/local/bin" "$dest/usr/local/lib" "$dest/etc/sudoers.d"
install -m 0755 "${owner[@]}" "$GPU_DIR/pruefstand-cluster" "$wrapper_dst"
install -m 0644 "${owner[@]}" "$stage/allow" "$allow_dst"
install -m 0440 "${owner[@]}" "$stage/sudoers" "$sudoers_dst"
echo "installed $wrapper_dst, $allow_dst and $sudoers_dst (commit $commit)"
