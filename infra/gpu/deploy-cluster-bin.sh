#!/usr/bin/env bash
# deploy-cluster-bin.sh [--check] [--bin-dev] [--print-sums]: copy the cluster scripts over SSH (VM; ADR-0019, A11-M11).
#
# Renders cluster.env from infra/cluster/cluster.env.template (every line must be a plain KEY=VALUE; nothing is
# executed), then copies infra/cluster/*.sh and cluster.env to /data/dheena/pruefstand-bin/ on the cluster with
# `cat > <name>.partial && mv <name>.partial <name>` and writes SHA256SUMS (cluster.env included) last. A few KB.
# Needs NO lock. It talks to the cluster with plain ssh, so it runs as the service user (the only holder of the cluster
# key): as the owner `sudo -u pruefstand infra/gpu/deploy-cluster-bin.sh`. Any user other than the service user (or
# --bin-dev) writes /data/dheena/pruefstand-bin-dev/ instead, so a dev checkout never replaces the trusted scripts.
# Confused-deputy guard (M3): it deploys only a tree equal to origin/main (lib/git_verify.sh); `make gpu-deploy-bin`
# exports origin/main with `git archive` and runs the exported copy. --check and --print-sums only read and skip it.
# --check: compare the remote SHA256SUMS with this checkout's and exit 1 if they differ; writes nothing.
# --print-sums: print the SHA256SUMS this checkout would deploy (no ssh); health.sh compares against it (exit 14).
# Env: CLUSTER_SSH_HOST (alias), PRUEFSTAND_SERVICE_USER (default pruefstand), CLUSTER_ENV_TEMPLATE (test seam).
# Exit: 0 ok, 1 differs / refused template / copy failed, 64 usage.
set -euo pipefail

GPU_DIR="$(cd "$(dirname "$0")" && pwd)"
CLUSTER_SRC="$GPU_DIR/../cluster"
TEMPLATE="${CLUSTER_ENV_TEMPLATE:-$CLUSTER_SRC/cluster.env.template}"
BASE="/data/dheena/pruefstand-bin"
usage="usage: deploy-cluster-bin.sh [--check] [--bin-dev] [--print-sums]"

check=0
dev=0
print=0
for arg in "$@"; do
  case "$arg" in
    --check) check=1 ;;
    --bin-dev) dev=1 ;;
    --print-sums) print=1 ;;
    *) echo "$usage" >&2; exit 64 ;;
  esac
done
[ "$(id -un)" = "${PRUEFSTAND_SERVICE_USER:-pruefstand}" ] || dev=1
dir="$BASE"
[ "$dev" -eq 0 ] || dir="$BASE-dev"
host="${CLUSTER_SSH_HOST:-cairo-s101lp}"
host_re='^[A-Za-z0-9][A-Za-z0-9._-]*$'
[[ $host =~ $host_re ]] || { echo "invalid CLUSTER_SSH_HOST" >&2; exit 64; }

stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT

staged_names() { # the files of the stage dir except SHA256SUMS, sorted
  local f
  for f in "$stage"/*; do
    [ "${f##*/}" = SHA256SUMS ] || echo "${f##*/}"
  done | LC_ALL=C sort
}

render() {
  local line
  # shellcheck disable=SC2016  # the \$ is literal: a value may start with the text \$HOME
  local re='^[A-Z][A-Z0-9_]*=(\$HOME)?[A-Za-z0-9_./:,@%+=-]*$'
  {
    echo "# generated by deploy-cluster-bin.sh from cluster.env.template; do not edit"
    while IFS= read -r line || [ -n "$line" ]; do
      case "$line" in '') continue ;; '#'*) continue ;; esac
      [[ $line =~ $re ]] || { echo "deploy-cluster-bin.sh: refused template line (only KEY=VALUE with a plain value)" >&2; return 1; }
      echo "$line"
    done <"$TEMPLATE"
  } >"$stage/cluster.env"
  cp "$CLUSTER_SRC"/*.sh "$stage/"
  mapfile -t names < <(staged_names)
  (cd "$stage" && sha256sum "${names[@]}" >SHA256SUMS)
}

render || exit 1
if [ "$print" -eq 1 ]; then
  cat "$stage/SHA256SUMS"
  exit 0
fi

if [ "$check" -eq 0 ]; then
  # shellcheck source=lib/git_verify.sh
  . "$GPU_DIR/lib/git_verify.sh"
  verify_reviewed_tree "$(cd "$GPU_DIR/../.." && pwd)"
fi

remote_ssh() { ssh -o BatchMode=yes -o ConnectTimeout=15 "$host" "$@"; }

if [ "$check" -eq 1 ]; then
  if remote="$(remote_ssh "cat $dir/SHA256SUMS" 2>/dev/null)" && [ "$remote" = "$(cat "$stage/SHA256SUMS")" ]; then
    echo "cluster scripts in $dir match this checkout"
    exit 0
  fi
  echo "cluster scripts in $dir are out of date or missing: run deploy-cluster-bin.sh" >&2
  exit 1
fi

remote_ssh "mkdir -p $dir"
mapfile -t names < <(staged_names)
for file in "${names[@]}" SHA256SUMS; do
  remote_ssh "cat > $dir/$file.partial && mv -f $dir/$file.partial $dir/$file" <"$stage/$file"
done
echo "deployed $((${#names[@]} + 1)) files to $dir"
