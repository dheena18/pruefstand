def test_the_bin_dir_placeholder_and_unknown_ones(repo: Repo, tmp_path: Path) -> None:
    custom = tmp_path / "t.template"
    custom.write_text("A=@BIN_DIR@/x\n", encoding="utf-8")
    ok = _deploy(repo, "--print-sums", CLUSTER_ENV_TEMPLATE=str(custom))
    assert ok.rc == 0
