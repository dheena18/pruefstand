# --- cluster_op as the service user ---


def test_cluster_op_builds_the_remote_path_from_the_root(stubs: Stubs, tmp_path: Path) -> None:
    fake_ssh(stubs, tmp_path)
    caller = stubs.root / "op.sh"
    caller.write_text(f'. "{GPU_DIR}/lib/cluster_ssh.sh"\ncluster_op status\n', encoding="utf-8")
    env = {"PRUEFSTAND_SERVICE_USER": getpass.getuser(), "PRUEFSTAND_CLUSTER_DATA_ROOT": "/data/zz"}
    run_script(caller, stubs=stubs, env=env)
    assert any("bash /data/zz/pruefstand-bin/status.sh" in c for c in stubs.calls("ssh"))
    run_script(caller, stubs=stubs, env={**env, "PRUEFSTAND_BIN_DEV": "1"})
    assert any("bash /data/zz/pruefstand-bin-dev/status.sh" in c for c in stubs.calls("ssh"))


