"""T3.1c CPU tests: the owner-supplied cluster data root and the trust rules for its file.

All values are synthetic (``/data/example``): the real cluster paths are not in the public repo.
"""

import os
from pathlib import Path

import pytest
from gpu_testkit import GPU_DIR, SYNTH_ROOT, run_script
from vm_testkit import Result, Stubs

PATHS = GPU_DIR / "lib" / "cluster_paths.sh"
HEADER = "# generated by deploy-cluster-bin.sh from cluster.env.template; do not edit\n"


def _root(stubs: Stubs, **env: str) -> Result:
    env.setdefault("PRUEFSTAND_CLUSTER_ROOT_FILE_UID", str(os.getuid()))
    script = stubs.root / "root.sh"
    script.write_text(f'. "{PATHS}"\ncluster_data_root\n', encoding="utf-8")
    return run_script(script, stubs=stubs, env=env)


def test_the_env_variable_wins_over_the_file(stubs: Stubs, tmp_path: Path) -> None:
    file = tmp_path / "root"
    file.write_text("/data/from-file\n", encoding="utf-8")
    env = {
        "PRUEFSTAND_CLUSTER_DATA_ROOT": SYNTH_ROOT,
        "PRUEFSTAND_CLUSTER_DATA_ROOT_FILE": str(file),
    }
    res = _root(stubs, **env)
    assert (res.rc, res.out.strip()) == (0, SYNTH_ROOT)


def test_the_file_is_read_when_no_variable_is_set(stubs: Stubs, tmp_path: Path) -> None:
    file = tmp_path / "root"
    file.write_text("/data/from-file\nignored second line\n", encoding="utf-8")
    file.chmod(0o644)
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT_FILE=str(file))
    assert (res.rc, res.out.strip()) == (0, "/data/from-file")


def test_nothing_configured_exits_78_and_names_both_sources(stubs: Stubs, tmp_path: Path) -> None:
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT_FILE=str(tmp_path / "missing"))
    assert res.rc == 78
    assert "PRUEFSTAND_CLUSTER_DATA_ROOT" in res.err
    assert "missing" in res.err


@pytest.mark.parametrize(
    "bad", ["relative/path", "/data/x/", "/data/../etc", "/data/$HOME", "/data/a b", "/data/a;b"]
)
def test_an_unsafe_root_is_refused_without_echoing_it(stubs: Stubs, bad: str) -> None:
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT=bad)
    assert res.rc == 78
    assert bad not in res.err


# --- the file source is trusted only when root could have written it ---


def _file_root(stubs: Stubs, tmp_path: Path, text: str, mode: int = 0o644) -> Result:
    file = tmp_path / "cluster-data-root"
    file.write_text(text, encoding="utf-8")
    file.chmod(mode)
    return _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT_FILE=str(file))


def test_a_trusted_file_is_read(stubs: Stubs, tmp_path: Path) -> None:
    res = _file_root(stubs, tmp_path, "/data/from-file\n")
    assert res.rc == 0
    assert res.out.strip() == "/data/from-file"


def test_a_symlinked_file_is_refused(stubs: Stubs, tmp_path: Path) -> None:
    real = tmp_path / "real"
    real.write_text("/data/from-file\n", encoding="utf-8")
    link = tmp_path / "link"
    link.symlink_to(real)
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT_FILE=str(link))
    assert res.rc == 78
    assert "symlink" in res.err
    assert "/data/from-file" not in res.out + res.err


@pytest.mark.parametrize("mode", [0o666, 0o664, 0o646, 0o622])
def test_a_group_or_world_writable_file_is_refused(stubs: Stubs, tmp_path: Path, mode: int) -> None:
    res = _file_root(stubs, tmp_path, "/data/from-file\n", mode)
    assert res.rc == 78
    assert "not writable" in res.err


def test_a_file_owned_by_another_uid_is_refused(stubs: Stubs, tmp_path: Path) -> None:
    file = tmp_path / "cluster-data-root"
    file.write_text("/data/from-file\n", encoding="utf-8")
    file.chmod(0o644)
    other = str(os.getuid() + 1)
    res = _root(
        stubs, PRUEFSTAND_CLUSTER_DATA_ROOT_FILE=str(file), PRUEFSTAND_CLUSTER_ROOT_FILE_UID=other
    )
    assert res.rc == 78
    assert "owned by root" in res.err


def test_a_file_in_a_writable_directory_is_refused(stubs: Stubs, tmp_path: Path) -> None:
    sub = tmp_path / "etc"
    sub.mkdir()
    (sub / "cluster-data-root").write_text("/data/from-file\n", encoding="utf-8")
    (sub / "cluster-data-root").chmod(0o644)
    sub.chmod(0o777)
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT_FILE=str(sub / "cluster-data-root"))
    assert res.rc == 78
    assert "directory" in res.err


def test_a_non_ascii_value_is_refused_even_under_a_utf8_locale(
    stubs: Stubs, tmp_path: Path
) -> None:
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT="/data/" + "caf\u00e9", LC_ALL="C.UTF-8")
    assert res.rc == 78
    assert "invalid" in res.err
    res = _file_root(stubs, tmp_path, "/data/" + "caf\u00e9\n")
    assert res.rc == 78


def test_an_overlong_value_is_refused(stubs: Stubs) -> None:
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT="/" + "a" * 4096)
    assert res.rc == 78
    assert "4096" in res.err
    assert _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT="/" + "a" * 4095).rc == 0
