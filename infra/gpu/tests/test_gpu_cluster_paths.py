# --- no real cluster path in tracked files ---


def test_no_tracked_file_names_a_real_cluster_data_root() -> None:
    """Only synthetic roots may appear next to the fixed sub-names (the owner supplies it)."""
    top = GPU_DIR.parents[1]
    files = subprocess.run(  # noqa: S603
        ["git", "-C", str(top), "ls-files"],  # noqa: S607
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()
    subs = r"(?:Models|pruefstand-bin|ollama\.log|truenas-ollama|rclone)"
    pat = re.compile(rf"/data/([A-Za-z0-9_-]+)/{subs}")
    allowed = {"example", "exuser", "one", "two", "zz", "other", "from-file", "someone"}
    hits = []
    for name in files:
        path = top / name
        if not path.is_file() or name == "infra/gpu/tests/test_gpu_cluster_paths.py":
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        hits += [f"{name}: {m.group(0)}" for m in pat.finditer(text) if m.group(1) not in allowed]
    assert not hits, hits[:5]
