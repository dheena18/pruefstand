PATHS = GPU_DIR / "lib" / "cluster_paths.sh"
HEADER = "# generated by deploy-cluster-bin.sh from cluster.env.template; do not edit\n"


def _root(stubs: Stubs, **env: str) -> Result:
    script = stubs.root / "root.sh"
    script.write_text(f'. "{PATHS}"\ncluster_data_root\n', encoding="utf-8")
    return run_script(script, stubs=stubs, env=env)


def test_the_env_variable_wins_over_the_file(stubs: Stubs, tmp_path: Path) -> None:
    file = tmp_path / "root"
    file.write_text("/data/from-file\n", encoding="utf-8")
    env = {
        "PRUEFSTAND_CLUSTER_DATA_ROOT": SYNTH_ROOT,
        "PRUEFSTAND_CLUSTER_DATA_ROOT_FILE": str(file),
    }
    res = _root(stubs, **env)
    assert (res.rc, res.out.strip()) == (0, SYNTH_ROOT)


def test_the_file_is_read_when_no_variable_is_set(stubs: Stubs, tmp_path: Path) -> None:
    file = tmp_path / "root"
    file.write_text("/data/from-file\nignored second line\n", encoding="utf-8")
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT_FILE=str(file))
    assert (res.rc, res.out.strip()) == (0, "/data/from-file")


def test_nothing_configured_exits_78_and_names_both_sources(stubs: Stubs, tmp_path: Path) -> None:
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT_FILE=str(tmp_path / "missing"))
    assert res.rc == 78
    assert "PRUEFSTAND_CLUSTER_DATA_ROOT" in res.err
    assert "missing" in res.err


@pytest.mark.parametrize(
    "bad", ["relative/path", "/data/x/", "/data/../etc", "/data/$HOME", "/data/a b", "/data/a;b"]
)
def test_an_unsafe_root_is_refused_without_echoing_it(stubs: Stubs, bad: str) -> None:
    res = _root(stubs, PRUEFSTAND_CLUSTER_DATA_ROOT=bad)
    assert res.rc == 78
    assert bad not in res.err


# --- deploy: rendering ---


@pytest.fixture(autouse=True)
def _link(stubs: Stubs) -> None:
    link_tools(stubs)


def _expected_env(template: Path, root: str) -> str:
    """An independent rendering of the template (python, not the shell code under test)."""
    out = HEADER
    for line in template.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            val = line.replace("@MODELS_DIR@", f"{root}/Models").replace(
                "@LOG@", f"{root}/ollama.log"
            )
            out += val.replace("@BIN_DIR@", f"{root}/pruefstand-bin") + "\n"
    return out


def _deploy(repo: Repo, *args: str, **env: str) -> Result:
    full = {"CLUSTER_SSH_HOST": "cairo-s101lp", **env}
    return repo.run("deploy-cluster-bin.sh", *args, **full)


def test_the_template_holds_placeholders_and_no_real_path() -> None:
    text = (CLUSTER_DIR / "cluster.env.template").read_text(encoding="utf-8")
    assert "OLLAMA_MODELS=@MODELS_DIR@\n" in text
    assert "OLLAMA_LOG=@LOG@\n" in text
    assert "@BIN_DIR@" in text
    assert not re.search(r"/data/", text)


def test_rendered_cluster_env_is_exact_and_deterministic(repo: Repo, tmp_path: Path) -> None:
    remote = tmp_path / "remote"
    remote.mkdir()
    fake_ssh(repo.stubs, remote)
    template = repo.root / "infra/cluster/cluster.env.template"
    assert _deploy(repo).rc == 0
    first = (remote / "pruefstand-bin/cluster.env").read_bytes()
    sums = (remote / "pruefstand-bin/SHA256SUMS").read_bytes()
    assert first.decode() == _expected_env(template, SYNTH_ROOT)
    assert _deploy(repo).rc == 0
    assert (remote / "pruefstand-bin/cluster.env").read_bytes() == first
    assert (remote / "pruefstand-bin/SHA256SUMS").read_bytes() == sums


def test_integrity_hash_logic_is_unchanged(repo: Repo, tmp_path: Path) -> None:
    """SHA256SUMS = sha256sum of every deployed file but itself, sorted, cluster.env included."""
    remote = tmp_path / "remote"
    remote.mkdir()
    fake_ssh(repo.stubs, remote)
    assert _deploy(repo).rc == 0
    target = remote / "pruefstand-bin"
    lines = (target / "SHA256SUMS").read_text().splitlines()
    names = [ln.split("  ", 1)[1] for ln in lines]
    assert names == sorted(names)
    assert "cluster.env" in names
    assert "SHA256SUMS" not in names
    for ln in lines:
        digest, name = ln.split("  ", 1)
        assert hashlib.sha256((target / name).read_bytes()).hexdigest() == digest
    printed = _deploy(repo, "--print-sums")
    assert printed.out == (target / "SHA256SUMS").read_text()


def test_a_different_root_changes_only_the_three_paths(repo: Repo) -> None:
    a = _deploy(repo, "--print-sums", PRUEFSTAND_CLUSTER_DATA_ROOT="/data/one")
    b = _deploy(repo, "--print-sums", PRUEFSTAND_CLUSTER_DATA_ROOT="/data/two")
    assert a.rc == b.rc == 0
    rows = zip(a.out.splitlines(), b.out.splitlines(), strict=True)
    changed = [x.split("  ")[1] for x, y in rows if x != y]
    assert changed == ["cluster.env"]


