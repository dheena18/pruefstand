"""T3.1a CPU tests: the installer and the deploy refuse an unreviewed tree (M3, confused deputy).

Both run with the owner's rights (sudo / the cluster key), so they only act on a tree that equals
``origin/main`` for ``infra/gpu`` and ``infra/cluster``. The tests use temp git repos with a bare
``origin`` and a ``DESTDIR``; the real ``/etc`` and ``/usr/local`` are never touched.
"""

import re
import shutil
from pathlib import Path

import pytest
from gpu_repo import Repo
from gpu_testkit import GPU_DIR, fake_ssh
from vm_testkit import Result

MARKER = "installed-by: infra/gpu/install-cluster-wrapper.sh"


def _install(repo: Repo, *args: str) -> Result:
    return repo.run("install-cluster-wrapper.sh", *args, DESTDIR=str(repo.dest))


def test_a_clean_tree_installs_and_prints_the_commit(repo: Repo) -> None:
    res = _install(repo)
    assert res.rc == 0, res.err
    assert repo.git("rev-parse", "HEAD") in res.out
    assert (repo.dest / "usr/local/bin/pruefstand-cluster").is_file()


def test_the_allow_list_is_generated_from_the_catalogue(repo: Repo) -> None:
    assert _install(repo).rc == 0
    allow = (repo.dest / "usr/local/lib/pruefstand-cluster.allow").read_text()
    assert allow.startswith("# generated by install-cluster-wrapper.sh")
    assert "bge-m3\t1157672605\n" in allow
    assert "gemma3:12b\t8164039732\n" in allow
    assert "BAAI" not in allow  # the cpu reranker is not an Ollama tag


@pytest.mark.parametrize("script", ["install-cluster-wrapper.sh", "deploy-cluster-bin.sh"])
@pytest.mark.parametrize("change", ["edit_gpu", "edit_cluster", "untracked", "staged", "ahead"])
def test_an_unreviewed_tree_is_refused_before_anything_is_written(
    repo: Repo, tmp_path: Path, script: str, change: str
) -> None:
    remote_root = tmp_path / "remote"
    remote_root.mkdir()
    fake_ssh(repo.stubs, remote_root)
    gpu_file = repo.root / "infra/gpu/pruefstand-cluster"
    if change == "edit_gpu":
        gpu_file.write_text(gpu_file.read_text() + "\ntouch /tmp/pwned\n")
    elif change == "edit_cluster":
        status = repo.root / "infra/cluster/status.sh"
        status.write_text(status.read_text() + "\nid\n")
    elif change == "untracked":
        (repo.root / "infra/cluster/evil.sh").write_text("id\n")
    elif change == "staged":
        gpu_file.write_text(gpu_file.read_text() + "\n# x\n")
        repo.git("add", "-A")
    else:  # a local commit that origin/main does not have
        gpu_file.write_text(gpu_file.read_text() + "\n# x\n")
        repo.git("commit", "-q", "-am", "local")
    res = (
        repo.run(script, DESTDIR=str(repo.dest))
        if script.startswith("install")
        else repo.run(script)
    )
    assert res.rc == 1, res.out + res.err
    assert "origin/main" in res.err
    assert not repo.dest.exists()
    assert not list(remote_root.rglob("*"))
    assert not repo.stubs.calls("ssh")


def test_read_only_modes_of_the_deploy_do_not_need_a_clean_tree(repo: Repo) -> None:
    (repo.root / "infra/cluster/evil.sh").write_text("id\n")
    assert repo.run("deploy-cluster-bin.sh", "--print-sums").rc == 0
    assert "evil.sh" in repo.run("deploy-cluster-bin.sh", "--print-sums").out


def test_the_deploy_of_a_clean_tree_prints_the_commit_and_copies(
    repo: Repo, tmp_path: Path
) -> None:
    remote_root = tmp_path / "remote"
    remote_root.mkdir()
    fake_ssh(repo.stubs, remote_root)
    res = repo.run("deploy-cluster-bin.sh")
    assert res.rc == 0, res.err
    assert repo.git("rev-parse", "HEAD") in res.out
    assert (remote_root / "pruefstand-bin" / "SHA256SUMS").is_file()


def test_the_untracked_check_also_sees_ignored_files_but_not_pycache(repo: Repo) -> None:
    (repo.root / ".gitignore").write_text("*.hidden\n__pycache__/\n")
    repo.git("add", "-A")
    repo.git("commit", "-q", "-m", "ignore")
    repo.git("push", "-q", "origin", "main")
    (repo.root / "infra/gpu/__pycache__").mkdir()
    (repo.root / "infra/gpu/__pycache__/x.pyc").write_text("x")
    assert _install(repo).rc == 0
    shutil.rmtree(repo.dest)
    (repo.root / "infra/cluster/payload.hidden").write_text("id\n")
    assert _install(repo).rc == 1


def test_an_existing_foreign_wrapper_is_not_overwritten(repo: Repo) -> None:
    target = repo.dest / "usr/local/bin/pruefstand-cluster"
    target.parent.mkdir(parents=True)
    target.write_text("#!/bin/sh\necho somebody else's file\n")
    res = _install(repo)
    assert res.rc == 1
    assert "not created by" in res.err
    assert "somebody else" in target.read_text()
    assert not (repo.dest / "etc/sudoers.d/pruefstand-cluster").exists()


def test_an_existing_foreign_sudoers_file_is_not_overwritten(repo: Repo) -> None:
    sudoers = repo.dest / "etc/sudoers.d/pruefstand-cluster"
    sudoers.parent.mkdir(parents=True)
    sudoers.write_text("ALL ALL=(ALL) NOPASSWD: ALL\n")
    res = _install(repo)
    assert res.rc == 1
    assert "NOPASSWD: ALL" in sudoers.read_text()
    assert not (repo.dest / "usr/local/bin/pruefstand-cluster").exists()


def test_replace_prints_a_diff_first_and_then_replaces(repo: Repo) -> None:
    target = repo.dest / "usr/local/bin/pruefstand-cluster"
    target.parent.mkdir(parents=True)
    target.write_text("#!/bin/sh\necho foreign\n")
    res = _install(repo, "--replace")
    assert res.rc == 0, res.err
    assert re.search(r"^[-+]echo foreign|^-echo foreign", res.out, re.M)
    assert MARKER in target.read_text()
    source = (repo.root / "infra/gpu/pruefstand-cluster").read_text()
    line = 'bin="/data/example/pruefstand-bin"'
    rendered = re.sub(r'^bin="@BIN_DIR@"$', line, source, flags=re.M)
    assert target.read_text() == rendered


def test_our_own_earlier_install_is_updated_without_replace(repo: Repo) -> None:
    assert _install(repo).rc == 0
    assert "already installed" in _install(repo).out
    gpu_file = repo.root / "infra/gpu/pruefstand-cluster"
    gpu_file.write_text(gpu_file.read_text() + "\n# reviewed change\n")
    repo.git("commit", "-q", "-am", "reviewed")
    repo.git("push", "-q", "origin", "main")
    res = _install(repo)
    assert res.rc == 0, res.err
    assert "reviewed change" in (repo.dest / "usr/local/bin/pruefstand-cluster").read_text()


def test_the_wrapper_carries_the_marker_header() -> None:
    assert MARKER in (GPU_DIR / "pruefstand-cluster").read_text()


def test_the_sudoers_file_is_checked_with_visudo_before_it_is_installed(repo: Repo) -> None:
    assert _install(repo).rc == 0
    assert repo.stubs.calls("visudo")[0].startswith("visudo -c -f ")
    assert (repo.dest / "etc/sudoers.d/pruefstand-cluster").is_file()


def test_a_sudoers_file_that_fails_visudo_is_not_installed(repo: Repo) -> None:
    repo.stubs.add("visudo", [("-c -f *", "syntax error", 1)])
    res = _install(repo)
    assert res.rc != 0
    assert not (repo.dest / "etc/sudoers.d/pruefstand-cluster").exists()
    assert not (repo.dest / "usr/local/bin/pruefstand-cluster").exists()
