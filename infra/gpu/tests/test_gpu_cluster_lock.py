"""T3.1a CPU tests: the wrapper's lock proof with the REAL ``pruefstand-lock`` (B1, M1)."""

import shutil
import subprocess
from pathlib import Path

import pytest
from gpu_testkit import GPU_DIR, rendered_wrapper, run_script
from gpu_world import ENTRIES, GpuWorld
from vm_testkit import Result

WRAPPER = GPU_DIR / "pruefstand-cluster"


def _allow(gpu: GpuWorld) -> str:
    path = gpu.root / "cluster.allow"
    rows = [f"{tag}\t{e['disk_bytes']}" for tag, e in ENTRIES.items() if e["engine"] == "ollama"]
    path.write_text("# generated by install-cluster-wrapper.sh\n" + "\n".join(rows) + "\n")
    return str(path)


def _env_for(gpu: GpuWorld) -> dict[str, str]:
    return {
        "PATH": str(gpu.stubs.bin), "HOME": str(gpu.root),
        "PRUEFSTAND_LOCK_DIR": str(gpu.lock_dir), "PRUEFSTAND_CLUSTER_ALLOW": _allow(gpu),
    }  # fmt: skip


def _ssh(gpu: GpuWorld) -> list[str]:
    return gpu.stubs.calls("ssh")


def _wrap(gpu: GpuWorld, *args: str) -> Result:
    env = {**_env_for(gpu), "CLUSTER_SSH_HOST": "cairo-s101lp"}
    return run_script(rendered_wrapper(gpu.root), *args, stubs=gpu.stubs, env=env)


LOCK_WRAPPER = GPU_DIR.parent / "vm" / "pruefstand-lock"


def _through_the_real_lock(
    gpu: GpuWorld, *args: str, timeout: str = "5"
) -> subprocess.CompletedProcess[str]:
    """Run the wrapper as production does: ``pruefstand-lock <wrapper> <op>`` (stub ssh)."""
    env = _env_for(gpu)  # PRUEFSTAND_LOCK_HELD stays unset: the real pruefstand-lock sets it
    env["GPU_LOCK_TIMEOUT_S"] = timeout
    return subprocess.run(  # noqa: S603
        ["bash", str(LOCK_WRAPPER), "bash", str(rendered_wrapper(gpu.root)), *args],  # noqa: S607
        env=env, capture_output=True, text=True, check=False, timeout=60,
    )  # fmt: skip


@pytest.mark.parametrize("op", ["stop-ollama", "start-ollama", "pull bge-m3"])
def test_the_lock_taken_by_the_real_pruefstand_lock_is_accepted(gpu: GpuWorld, op: str) -> None:
    """B1: the holder recorded in /proc/locks must be an ancestor, not a dead flock child."""
    proc = _through_the_real_lock(gpu, *op.split())
    assert proc.returncode == 0, proc.stderr
    assert len(_ssh(gpu)) == 1


def test_an_unrelated_holder_blocks_the_real_pruefstand_lock_and_nothing_runs(
    gpu: GpuWorld,
) -> None:
    flock = shutil.which("flock") or "flock"
    holder = subprocess.Popen(  # noqa: S603
        [flock, str(gpu.lock_dir / "gpu.lock"), "sh", "-c", "echo ready; sleep 30"],
        stdout=subprocess.PIPE, text=True,
    )  # fmt: skip
    try:
        assert holder.stdout is not None
        assert holder.stdout.readline().strip() == "ready"
        proc = _through_the_real_lock(gpu, "stop-ollama", timeout="1")
    finally:
        holder.kill()
        holder.wait()
    assert proc.returncode == 75
    assert not _ssh(gpu)


def test_a_tag_that_is_only_a_prefix_of_an_allowed_tag_is_refused(gpu: GpuWorld) -> None:
    assert "qwen3:4b\t" in Path(_allow(gpu)).read_text()
    assert _wrap(gpu, "show", "qwen3").rc == 64
    assert _wrap(gpu, "show", "qwen3:4").rc == 64
    assert _wrap(gpu, "show", "qwen3:4b").rc == 0
