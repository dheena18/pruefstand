def test_mutating_ops_run_while_an_ancestor_holds_the_lock(gpu: GpuWorld) -> None:
    with (gpu.lock_dir / "gpu.lock").open("rb") as holder:
        fcntl.flock(holder, fcntl.LOCK_EX)  # this test process is the wrapper's ancestor
        res = _wrap(gpu, "stop-ollama", held=True)
    assert res.rc == 0, res.err
    assert f"bash {BIN}/stop-ollama.sh" in _ssh(gpu)[0]


def _env_for(gpu: GpuWorld) -> dict[str, str]:
    return {
        "PATH": str(gpu.stubs.bin), "HOME": str(gpu.root), "PRUEFSTAND_LOCK_HELD": "1",
        "PRUEFSTAND_LOCK_DIR": str(gpu.lock_dir), "PRUEFSTAND_CLUSTER_ALLOW": str(_allow(gpu)),
    }  # fmt: skip


def test_the_lock_holder_may_be_a_distant_ancestor(gpu: GpuWorld) -> None:
    """pruefstand-lock -> make -> sudo -> wrapper: the holder is not the direct parent."""
    flock = shutil.which("flock") or "flock"
    script = f"bash {WRAPPER} stop-ollama; exit $?"
    lock = str(gpu.lock_dir / "gpu.lock")
    proc = subprocess.run(  # noqa: S603
        [flock, lock, "bash", "-c", f"bash -c '{script}'"],
        env=_env_for(gpu), capture_output=True, text=True, check=False, timeout=30,
    )  # fmt: skip
    assert proc.returncode == 0, proc.stderr
    assert f"bash {BIN}/stop-ollama.sh" in _ssh(gpu)[0]


@pytest.mark.parametrize("op", ["stop-ollama", "start-ollama", "pull bge-m3", "rm gemma3:12b"])
def test_a_lock_held_by_an_unrelated_process_is_no_proof(gpu: GpuWorld, op: str) -> None:
    """The executor holds the lock during a gate run: that must not let an agent act (M1)."""
    (gpu.lock_dir / "MAINTENANCE").touch()
    flock = shutil.which("flock") or "flock"
    holder = subprocess.Popen(  # noqa: S603
        [flock, str(gpu.lock_dir / "gpu.lock"), "sh", "-c", "echo ready; sleep 30"],
        stdout=subprocess.PIPE, text=True,
    )  # fmt: skip
    try:
        assert holder.stdout is not None
        assert holder.stdout.readline().strip() == "ready"
        res = _wrap(gpu, *op.split(), held=True)
    finally:
        holder.kill()
        holder.wait()
    assert res.rc == 2
    assert "not held by" in res.err
    assert not _ssh(gpu)


def test_ops_map_to_the_fixed_cluster_commands(gpu: GpuWorld) -> None:
    with (gpu.lock_dir / "gpu.lock").open("rb") as holder:
        fcntl.flock(holder, fcntl.LOCK_EX)
        (gpu.lock_dir / "MAINTENANCE").touch()
        for op in (("start-ollama",), ("pull", "bge-m3"), ("rm", "gemma3:12b")):
            assert _wrap(gpu, *op, held=True).rc == 0
    _wrap(gpu, "status")
    _wrap(gpu, "show", "qwen3.8:27b-q8_0")
    cmds = [c.split("cairo-s101lp ", 1)[1] for c in _ssh(gpu)]
    assert cmds == [
        f"bash {BIN}/start-ollama.sh", f"bash {BIN}/ollama-op.sh pull bge-m3 1157672605",
        f"bash {BIN}/ollama-op.sh rm gemma3:12b", f"bash {BIN}/status.sh",
        f"bash {BIN}/ollama-op.sh show qwen3.8:27b-q8_0",
    ]  # fmt: skip


