def test_cluster_ssh_validates_before_calling_anything(gpu: GpuWorld) -> None:
    gpu.stubs.add("sudo", [("*", "", 0)])
    assert _lib(gpu, "cluster_op rm 'x; reboot'").rc == 64
    assert _lib(gpu, "cluster_op reboot").rc == 64
    assert not _ssh(gpu)
    assert not gpu.stubs.calls("sudo")


def _lib(gpu: GpuWorld, call: str, **env: str) -> Result:
    harness = gpu.root / "harness.sh"
    harness.write_text(
        f'set -euo pipefail\n. "{GPU_DIR}/lib/cluster_ssh.sh"\n{call}\n', encoding="utf-8"
    )
    return run_script(harness, stubs=gpu.stubs, env=gpu.env(**env))


def test_the_sudoers_fragment_keeps_the_lock_flag_and_names_one_wrapper(gpu: GpuWorld) -> None:
    res = run_script(INSTALL, "--print-sudoers", stubs=gpu.stubs)
    assert res.rc == 0, res.err
    lines = res.out.splitlines()
    assert 'Defaults!/usr/local/bin/pruefstand-cluster env_keep += "PRUEFSTAND_LOCK_HELD"' in lines
    assert "%pruefstand ALL=(pruefstand) NOPASSWD: /usr/local/bin/pruefstand-cluster" in lines
    assert len([ln for ln in lines if ln and not ln.startswith("#")]) == 2


def test_install_refuses_without_root_and_changes_nothing(gpu: GpuWorld, tmp_path: Path) -> None:
    if os.geteuid() == 0:
        pytest.skip("running as root")
    res = run_script(INSTALL, stubs=gpu.stubs, env={"DESTDIR": ""})
    assert res.rc == 2
    assert "sudo" in res.err
    assert not list(tmp_path.glob("**/pruefstand-cluster*"))


def test_the_wrapper_is_self_contained_and_only_the_tag_pattern_is_accepted() -> None:
    text = WRAPPER.read_text(encoding="utf-8")
    assert "source " not in text
    assert not any(line.strip().startswith(". ") for line in text.splitlines())
    assert "^[a-z0-9._:/-]+$" in text


LOCK_WRAPPER = GPU_DIR.parent / "vm" / "pruefstand-lock"


def _through_the_real_lock(
    gpu: GpuWorld, *args: str, timeout: str = "5"
) -> subprocess.CompletedProcess[str]:
    """Run the wrapper as production does: ``pruefstand-lock <wrapper> <op>`` (stub ssh)."""
    env = _env_for(gpu)
    env.pop("PRUEFSTAND_LOCK_HELD")  # the real pruefstand-lock sets it
    env["GPU_LOCK_TIMEOUT_S"] = timeout
    return subprocess.run(  # noqa: S603
        ["bash", str(LOCK_WRAPPER), "bash", str(WRAPPER), *args],  # noqa: S607
        env=env, capture_output=True, text=True, check=False, timeout=60,
    )  # fmt: skip


@pytest.mark.parametrize("op", ["stop-ollama", "start-ollama", "pull bge-m3"])
def test_the_lock_taken_by_the_real_pruefstand_lock_is_accepted(gpu: GpuWorld, op: str) -> None:
    """B1: the holder recorded in /proc/locks must be an ancestor, not a dead flock child."""
    proc = _through_the_real_lock(gpu, *op.split())
    assert proc.returncode == 0, proc.stderr
    assert len(_ssh(gpu)) == 1


def test_an_unrelated_holder_blocks_the_real_pruefstand_lock_and_nothing_runs(
    gpu: GpuWorld,
) -> None:
    flock = shutil.which("flock") or "flock"
    holder = subprocess.Popen(  # noqa: S603
        [flock, str(gpu.lock_dir / "gpu.lock"), "sh", "-c", "echo ready; sleep 30"],
        stdout=subprocess.PIPE, text=True,
    )  # fmt: skip
    try:
        assert holder.stdout is not None
        assert holder.stdout.readline().strip() == "ready"
        proc = _through_the_real_lock(gpu, "stop-ollama", timeout="1")
    finally:
        holder.kill()
        holder.wait()
    assert proc.returncode == 75
    assert not _ssh(gpu)


def test_a_tag_that_is_only_a_prefix_of_an_allowed_tag_is_refused(gpu: GpuWorld) -> None:
    allow = _allow(gpu)
    assert "qwen3:4b\t" in allow.read_text()
    assert _wrap(gpu, "show", "qwen3").rc == 64
    assert _wrap(gpu, "show", "qwen3:4").rc == 64
    assert _wrap(gpu, "show", "qwen3:4b").rc == 0
