def test_env_example_and_normal_files_pass_and_big_files_do_not(lab: Lab) -> None:
    msg, body = _ready(lab, ".env.example")
    (lab.wt / "big.dat").write_bytes(b"0" * (1024 * 1024 + 1))
    rc, _, err = _push(lab, msg, body, "--add", ".env.example", "--add", "big.dat")
    assert rc == 2
    assert "big.dat (larger than 1 MB)" in err
    assert ".env.example (" not in err
    (lab.wt / "big.dat").unlink()
    git(lab.wt, "reset", "-q")
    assert _push(lab, msg, body, "--add", ".env.example")[0] == 0


def test_wrong_or_main_branch_is_refused(lab: Lab) -> None:
    msg, body = _ready(lab)
