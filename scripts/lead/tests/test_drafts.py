def test_dry_run_checks_everything_and_changes_nothing(lab: Lab) -> None:
    msg, body = _ready(lab)
    rc, out, err = _push(lab, msg, body, "--dry-run", "--add", "new.py")
    assert rc == 0, err
    assert "DRY-RUN" in out
    assert git(lab.wt, "log", "-1", "--format=%s") == "seed"
    assert git(lab.wt, "diff", "--cached", "--name-only") == ""  # the real index is untouched
    assert not lab.origin_has(BRANCH)
    assert lab.gh_log() == ""
    rc, _, err = _push(lab, msg, body, "--dry-run")  # new.py is untracked and not added
    assert rc == 2
    assert "new.py" in err


