"""Tests of draft_push.sh, draft_update.sh and install_wrappers.sh (real git, fake gh/git/uv)."""

import shutil
from pathlib import Path

import pytest
from lead.leadtestenv import LEAD, Lab, git

BRANCH = "feat/x"


def _push(lab: Lab, msg: Path, body: Path, *extra: str) -> tuple[int, str, str]:
    res = lab.run("draft_push.sh", *extra, str(lab.wt), BRANCH, "the title", str(msg), str(body))
    return res.returncode, res.stdout, res.stderr


def _ready(lab: Lab, name: str = "new.py") -> tuple[Path, Path]:
    lab.write(name, "Y = 2\n")
    return lab.msg("m.txt", "feat: add new\n"), lab.msg("b.md", "body\n")


def test_draft_push_commits_pushes_and_opens_a_draft_pr_against_main(lab: Lab) -> None:
    msg, body = _ready(lab)
    rc, out, err = _push(lab, msg, body, "--add", "new.py")
    assert rc == 0, out + err
    assert "pull/1" in out
    assert git(lab.wt, "log", "-1", "--format=%s") == "feat: add new"
    assert lab.origin_has(BRANCH)
    expected = (
        "pr create --draft --repo dheena18/pruefstand --base main --head feat/x --title the title"
    )
    assert expected in lab.gh_log()
    assert "--body-file" in lab.gh_log()


def test_the_push_names_exactly_this_branch_and_is_never_forced(lab: Lab) -> None:
    msg, body = _ready(lab)
    assert _push(lab, msg, body, "--add", "new.py")[0] == 0
    pushes = [ln for ln in lab.git_log().splitlines() if ln.startswith("push")]
    assert pushes == ["push -q -u origin refs/heads/feat/x:refs/heads/feat/x"]
    update = lab.msg("m2.txt", "fix: more\n")
    lab.write("new.py", "Y = 3\n")
    assert lab.run("draft_update.sh", str(lab.wt), BRANCH, str(update)).returncode == 0
    pushes = [ln for ln in lab.git_log().splitlines() if ln.startswith("push")]
    assert pushes[-1] == "push -q -u origin refs/heads/feat/x:refs/heads/feat/x"
    assert not any(" -f" in ln or "--force" in ln or " +" in ln for ln in pushes)


@pytest.mark.parametrize(
    "branch", ["+feat/x", "-f", "feat/x:main", "feat x", "../x", "feat/x.lock"]
)
def test_branch_names_that_could_become_refspecs_are_refused(lab: Lab, branch: str) -> None:
    msg, body = _ready(lab)
    res = lab.run("draft_push.sh", "--add", "new.py", str(lab.wt), branch, "t", str(msg), str(body))
    assert res.returncode == 2
    assert "invalid branch name" in res.stderr
    assert not any(ln.startswith("push") for ln in lab.git_log().splitlines())


BAD_TEXT = [
    "feat: x\n\nClaude-Session: https://claude.ai/code/session_1\n",
    "x\n\nClaude-Session : abc\n",
    "x\n\nclaude session: abc\n",
    "x\n\n🤖 Generated with [Claude Code](https://claude.com)\n",
    "generated with  claude   code\n",
    "Generated by Claude Code\n",
]


@pytest.mark.parametrize("bad", BAD_TEXT)
@pytest.mark.parametrize("which", ["msg", "body", "title"])
def test_footer_in_message_body_or_title_is_refused(lab: Lab, bad: str, which: str) -> None:
    lab.write("new.py", "Y = 2\n")
    msg = lab.msg("m.txt", bad if which == "msg" else "feat: ok\n")
    body = lab.msg("b.md", bad if which == "body" else "fine\n")
    title = bad.strip() if which == "title" else "the title"
    res = lab.run(
        "draft_push.sh", "--add", "new.py", str(lab.wt), BRANCH, title, str(msg), str(body)
    )
    assert res.returncode == 2
    assert "owner rule" in res.stderr
    assert not lab.origin_has(BRANCH)
    assert lab.gh_log() == ""
    assert git(lab.wt, "log", "-1", "--format=%s") == "seed"


def test_update_refuses_a_footer_too(lab: Lab) -> None:
    lab.write("a.py", "X = 2\n")
    msg = lab.msg("m.txt", "fix: x\n\nClaude-Session: abc\n")
    assert lab.run("draft_update.sh", str(lab.wt), BRANCH, str(msg)).returncode == 2
    assert not lab.origin_has(BRANCH)


def test_a_footer_added_by_a_commit_hook_is_caught_before_the_push(lab: Lab) -> None:
    hook = lab.wt / ".git" / "hooks" / "commit-msg"
    hook.write_text(
        '#!/bin/sh\nprintf "\\nClaude-Session: injected\\n" >> "$1"\n', encoding="utf-8"
    )
    hook.chmod(0o755)
    msg, body = _ready(lab)
    rc, _, err = _push(lab, msg, body, "--add", "new.py")
    assert rc == 2
    assert "committed message" in err
    assert not lab.origin_has(BRANCH)
    assert lab.gh_log() == ""


def test_ruff_failures_stop_before_commit(lab: Lab) -> None:
    msg, body = lab.msg("m.txt", "feat: x\n"), lab.msg("b.md", "b\n")
    lab.write("bad.py", "import os\n")
    rc, out, _ = _push(lab, msg, body, "--add", "bad.py")
    assert (rc, "RUFF_FAIL" in out) == (1, True)
    lab.write("bad.py", "x   =   1\n")
    rc, out, _ = _push(lab, msg, body, "--add", "bad.py")
    assert (rc, "FORMAT_FAIL" in out) == (1, True)
    assert git(lab.wt, "log", "-1", "--format=%s") == "seed"
    assert not lab.origin_has(BRANCH)


def test_untracked_files_are_refused_and_listed_but_tracked_changes_need_no_flag(lab: Lab) -> None:
    msg, body = _ready(lab)
    lab.write("stray.txt", "x\n")
    rc, _, err = _push(lab, msg, body)
    assert rc == 2
    assert "stray.txt" in err
    assert "new.py" in err
    assert not lab.origin_has(BRANCH)
    git(lab.wt, "reset", "-q")
    (lab.wt / "stray.txt").unlink()
    (lab.wt / "new.py").unlink()
    lab.write("a.py", "X = 5\n")  # a tracked file: no --add needed
    assert _push(lab, msg, body)[0] == 0
    assert git(lab.wt, "show", "HEAD:a.py") == "X = 5"


