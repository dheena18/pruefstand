#!/usr/bin/env bash
# usage: install_wrappers.sh [--dry-run] [--dir <bin-dir>] [--main <main-checkout>]
# Creates lead-draft-push, lead-draft-update and lead-resolve-merge in <bin-dir> (default ~/.local/bin). Each
# wrapper fetches origin/main in the MAIN checkout (default: the checkout this script belongs to, found through
# the git common dir), fast-forwards it when it is a clean `main`, and execs that checkout's scripts/lead/<name>.sh.
# So a worktree of a stale branch (which lacks scripts/lead/) can still use the current scripts. No sudo.
set -u -o pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
dry=0; dir="$HOME/.local/bin"; main=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --dry-run) dry=1; shift ;;
    --dir) [ "$#" -ge 2 ] || lead_die 2 "--dir needs a value"; dir="$2"; shift 2 ;;
    --main) [ "$#" -ge 2 ] || lead_die 2 "--main needs a value"; main="$2"; shift 2 ;;
    *) lead_die 2 "usage: install_wrappers.sh [--dry-run] [--dir <bin-dir>] [--main <main-checkout>]" ;;
  esac
done
if [ -z "$main" ]; then
  common="$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --path-format=absolute --git-common-dir)" \
    || lead_die 1 "not inside a git checkout"
  main="$(dirname "$common")"
fi
[ -d "$main" ] || lead_die 1 "main checkout not found: $main"
[ "$dry" = 1 ] || mkdir -p "$dir"
for pair in lead-draft-push:draft_push lead-draft-update:draft_update lead-resolve-merge:resolve_merge; do
  name="${pair%%:*}"; script="${pair##*:}.sh"
  if [ "$dry" = 1 ]; then echo "DRY-RUN: would write $dir/$name"; continue; fi
  {
    printf '#!/usr/bin/env bash\n# generated by scripts/lead/install_wrappers.sh\nMAIN=%q\n' "$main"
    cat <<'WRAP'
if git -C "$MAIN" fetch -q origin main 2>/dev/null; then
  if [ "$(git -C "$MAIN" symbolic-ref --short -q HEAD)" = main ] \
    && [ -z "$(git -C "$MAIN" status --porcelain --untracked-files=no)" ]; then
    git -C "$MAIN" merge -q --ff-only origin/main || echo "warning: could not fast-forward $MAIN" >&2
  else
    echo "warning: $MAIN is not a clean main; using its current scripts" >&2
  fi
else
  echo "warning: fetch failed; using $MAIN as it is" >&2
fi
WRAP
    printf 'exec "$MAIN/scripts/lead/%s" "$@"\n' "$script"
  } >"$dir/$name" && chmod +x "$dir/$name" && echo "wrote $dir/$name"
done
