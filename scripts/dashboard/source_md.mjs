// SOURCE.md of a fixture set (ui-spec §14.1): run ids, SHAs, date, state ids, the exact command of every
// derivation, the refused / error / `en` case ids. Deterministic: the date is the newest real run's `created_at`.
import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";

import { T83_STATES, caseFacts, statesOf } from "./states.mjs";

const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));
const list = (ids, max = 12) => (ids.length === 0 ? "none" : ids.slice(0, max).map((i) => `\`${i}\``).join(", ") + (ids.length > max ? `, … (${ids.length} in all)` : ""));

export function sourceMd({ raw, populated, ids }) {
  const { roles, sources = {} } = readJson(path.join(raw, "roles.json"));
  const real = Object.entries(roles).map(([role, id]) => {
    const run = readJson(path.join(raw, id, "run.json"));
    return { role, id, run, source: sources[role] };
  });
  const date = real.map((r) => r.run.created_at).sort().at(-1).slice(0, 10);
  const states = statesOf(populated);
  const facts = caseFacts(populated);
  const derivedRaw = readdirSync(raw).filter((n) => /^\d{8}T\d{6}-/.test(n) && !Object.values(roles).includes(n));
  const lines = [
    "# Dashboard fixtures: populated set",
    "",
    `Date: ${date}`,
    "",
    "Generated by `scripts/dashboard/refresh_snapshot.sh`; never edit by hand. Nothing here is invented: every run is a real tier-1 run (public slice) or derived from one through real Prüfstand code.",
    "",
    "## Real runs (GitHub Actions `live-e2e`)",
    "",
    "| Role | Run id | Git SHA | GitHub run | Artefact |",
    "| --- | --- | --- | --- | --- |",
    ...real.map((r) => `| ${r.role} | \`${r.id}\` | \`${(r.run.git_sha ?? "–").slice(0, 7)}\` | ${r.source?.github_run ?? "–"} | ${r.source?.artifact ?? "–"} |`),
    "",
    "## Derivations",
    "",
    "Raw level (`apps/dashboard/fixtures/raw/`), through real code:",
    "",
    "- `uv run python scripts/dashboard/derive.py` writes F-PARTIAL (F-T1 truncated to 5 cases, `budget_exceeded`), F-NO-BASELINE (`gate_from_store` against an empty `local_dir` store) and F-JUDGE-SKIPPED (judged values dropped, `run_gate` against F-BASE). Derived run ids: " + list(derivedRaw) + ".",
    "- `uv run pruefstand gate --config apps/dashboard/fixtures/raw/pruefstand.yaml --candidate <F-T1> --baseline <F-BASE>` re-gates F-T1 against the F-BASE of this snapshot.",
    "- F-BASE is the `live-baseline` artefact without its `gate.json` (it is a `main` run, not gated: S-NOT-GATED).",
    "",
    "Exported level:",
    "",
    "- `uv run pruefstand export-dashboard --runs apps/dashboard/fixtures/raw --out apps/dashboard/fixtures/populated`",
    `- \`node scripts/dashboard/derive_fixtures.mjs\` writes D-BASELINE-MISSING (\`${ids.missing}\`, baseline \`${ids.ghost}\` is not in the index), D-MANY (the 1,500-case run \`${ids.big}\`, dated newest, and older clones of F-T1; copies of cases keep every field but cut the answer to 240 characters (1 MB file cap); the clones outside the newest 20 are S-CASES-PRUNED) and the empty set (D-EMPTY).`,
    "",
    "## States (ui-spec §14.1)",
    "",
    ...Object.entries(states).map(([s, runs]) => `- ${s}: ${list(runs, 6)}`),
    `- Tier-2 rows added by T8.3 (allow-listed until then): ${T83_STATES.join(", ")}.`,
    "",
    "## Real cases the matrix needs",
    "",
    `- refused: ${list(facts.refused)}`,
    `- with an error: ${list(facts.error)}`,
    `- \`en\`: ${list(facts.en)}`,
    "",
    "Judge: the quota-less tier-1 runs of this snapshot have `judge_mode=skipped`; a `judge_mode=github` run (block J rows) is added when a live PR run has quota.",
    "",
  ];
  return lines.join("\n");
}

export function emptySourceMd(date) {
  return [
    "# Dashboard fixtures: empty set (D-EMPTY)",
    "",
    `Date: ${date}`,
    "",
    "`runs/index.json` with 0 runs, `labels.json` copied from the populated set, `manifest.json`. Written by `scripts/dashboard/derive_fixtures.mjs` (`refresh_snapshot.sh`).",
    "",
  ].join("\n");
}
