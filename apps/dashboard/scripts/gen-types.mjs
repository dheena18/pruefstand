// `pnpm gen:types`: TypeScript types from the JSON Schemas in schemas/ (ui-spec §2.4). Deterministic;
// CI regenerates and fails on a diff (job `types-fresh`).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const schemas = path.resolve(here, "../../../schemas");
const out = path.resolve(here, "../src/types/generated");

// file stem -> exported root type (the schema `title`)
const STEMS = {
    run_manifest: "RunManifest",
    gate_report: "GateReport",
    dashboard_run_index: "DashboardRunIndex",
    dashboard_slices: "DashboardSlices",
    dashboard_cases: "DashboardCases",
    labels: "LabelsDocument",
};

const BANNER =
    "/* eslint-disable */\n/**\n * Generated by `pnpm gen:types` from schemas/{stem}.schema.json. Do not edit.\n */";

mkdirSync(out, { recursive: true });
const barrel = ["// Generated by `pnpm gen:types`. Do not edit.", ""];
for (const [stem, root] of Object.entries(STEMS)) {
    const schema = JSON.parse(readFileSync(path.join(schemas, `${stem}.schema.json`), "utf8"));
    const text = await compile(schema, root, {
        bannerComment: BANNER.replace("{stem}", stem),
        additionalProperties: false,
        unreachableDefinitions: false,
        cwd: schemas,
    });
    writeFileSync(path.join(out, `${stem}.ts`), text);
    barrel.push(`export type { ${root} } from "./${stem}";`);
}
writeFileSync(path.join(out, "index.ts"), barrel.join("\n") + "\n");
console.log(`generated ${Object.keys(STEMS).length} schema types in src/types/generated`);
