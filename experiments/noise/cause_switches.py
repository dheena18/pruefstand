"""Tier-2 cause-switch scenarios: each rag-demo bug switch maps to its ``likely_cause`` (T6.3 S4).

Five candidates (``apps/rag-demo/configs/cause/*.yaml``, D1276) run against the unchanged
``rag.gpu.yaml`` on the real A40 stack. Each scenario gates **only** its target metric on
``overall`` (m = 1, ``experiments/noise/configs/scenario_<name>.yaml``), so the expected code is not
diluted by the Holm family. Before the cause is asserted, the MDE from the baseline's spread is
compared with the scenario's planned drop: an underpowered scenario fails with "scenario
underpowered: MDE x > expected drop y", never with a silent pass.

Judge plan (AI12-10, P4.3): the four deterministic scenarios run baseline and switch with
``PRUEFSTAND_JUDGE_MODE=skipped`` on ``core``; ``refusal_policy`` runs a fresh baseline and the
switch on the refusal stratum of ``full`` (``--split full --stratum refusal``, no ``--block``)
with the judge, never with a baseline from the store.

Usage::

    uv run python experiments/noise/cause_switches.py --write-configs
    uv run python experiments/noise/cause_switches.py --plan --scenarios all
    uv run python experiments/noise/cause_switches.py --check BASE SWITCH --scenarios language
"""

import argparse
import json
import math
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Literal

import numpy as np
import yaml
from pydantic import BaseModel, ConfigDict, JsonValue

from pruefstand.core.config import PruefstandConfig
from pruefstand.core.config_loader import load_config
from pruefstand.core.enums import GateStatus
from pruefstand.core.errors import ConfigError, PruefstandError
from pruefstand.core.models.gate import CauseCode, GateReport
from pruefstand.core.models.run import RunResults
from pruefstand.gate.policy import evaluate_gate
from pruefstand.gate.stats import minimum_detectable_effect
from pruefstand.metrics.registry import MetricRegistry
from pruefstand.store.artifacts import ArtifactStore

REPO = Path(__file__).resolve().parents[2]
BASE_CONFIG = REPO / "pruefstand.yaml"
CONFIG_DIR = Path(__file__).resolve().parent / "configs"
CAUSE_DIR = "apps/rag-demo/configs/cause"
HEADER = (
    "# Generated by experiments/noise/cause_switches.py --write-configs from pruefstand.yaml.\n"
)


class Scenario(BaseModel):
    """One bug switch: its candidate config, the metric gated alone and the expected cause."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    name: CauseCode
    candidate: str  # file name in apps/rag-demo/configs/cause/
    metric: str
    judged: bool = False  # refusal_policy only: judge on, refusal stratum of full
    expected_drop: float | None  # planned drop for the MDE pre-check; None = absolute check


SCENARIOS: tuple[Scenario, ...] = (
    Scenario(name="retrieval", candidate="retrieval_reranker_off_top3.yaml",
             metric="context_recall", expected_drop=0.10),
    Scenario(name="citation_format", candidate="no_citations.yaml",
             metric="citation_recall", expected_drop=0.20),
    Scenario(name="language", candidate="answer_language_en.yaml",
             metric="language_match", expected_drop=0.50),
    Scenario(name="refusal_policy", candidate="no_refusal.yaml",
             metric="refusal_correct", judged=True, expected_drop=0.30),
    Scenario(name="errors", candidate="errors_closed_port.yaml",
             metric="error_rate", expected_drop=None),
)  # fmt: skip
BY_NAME: Mapping[str, Scenario] = {s.name: s for s in SCENARIOS}


class ScenarioUnderpoweredError(PruefstandError):
    """The baseline's spread cannot detect the scenario's planned drop."""


class PlannedRun(BaseModel):
    """One ``pruefstand run`` of a scenario: the rag-demo config, the argv and the extra env."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    scenario: str
    role: Literal["baseline", "switch"]
    rag_config: str
    argv: tuple[str, ...]
    env: dict[str, str]


def select(names: Sequence[str]) -> list[Scenario]:
    """The scenarios named in ``names`` (``all`` = every scenario, in table order).

    Raises:
        ConfigError: an unknown name.
    """
    if list(names) == ["all"]:
        return list(SCENARIOS)
    unknown = sorted(set(names) - set(BY_NAME))
    if unknown:
        msg = f"unknown scenarios {unknown}; known: {list(BY_NAME)}"
        raise ConfigError(msg)
    return [BY_NAME[n] for n in names]


def scenario_config(base: Mapping[str, JsonValue], scenario: Scenario) -> dict[str, JsonValue]:
    """``base`` (``pruefstand.yaml``) gating only ``scenario.metric`` on ``overall``.

    Raises:
        ConfigError: the base config has no rule for the metric.
    """
    gate = base.get("gate")
    rules = gate.get("metrics") if isinstance(gate, Mapping) else None
    if not isinstance(gate, Mapping) or not isinstance(rules, Mapping):
        msg = "pruefstand.yaml: no gate.metrics mapping"
        raise ConfigError(msg)
    if scenario.metric not in rules:
        msg = f"pruefstand.yaml: no gate rule for {scenario.metric}"
        raise ConfigError(msg)
    narrowed: dict[str, JsonValue] = {
        **gate,
        "metrics": {scenario.metric: rules[scenario.metric]},
        "gated_slices": ["overall"],
    }
    return {**base, "gate": narrowed}


def write_configs(out: Path = CONFIG_DIR, base_path: Path = BASE_CONFIG) -> list[Path]:
    """Write ``scenario_<name>.yaml`` for every scenario; return the paths."""
    base = yaml.safe_load(base_path.read_text(encoding="utf-8"))
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for scenario in SCENARIOS:
        text = yaml.safe_dump(scenario_config(base, scenario), sort_keys=False, allow_unicode=True)
        path = out / f"scenario_{scenario.name}.yaml"
        path.write_text(HEADER + text, encoding="utf-8")
        paths.append(path)
    return paths


def plan(scenario: Scenario, out: Path) -> tuple[PlannedRun, PlannedRun]:
    """The baseline and switch runs of ``scenario`` (fresh baseline; judge plan as above)."""
    split = ("--split", "full", "--stratum", "refusal") if scenario.judged else ("--split", "core")
    env = {} if scenario.judged else {"PRUEFSTAND_JUDGE_MODE": "skipped"}
    config = str(CONFIG_DIR.relative_to(REPO) / f"scenario_{scenario.name}.yaml")

    def one(role: Literal["baseline", "switch"], rag: str) -> PlannedRun:
        argv = ("pruefstand", "run", "--config", config, "--tier", "nightly",
                "--out", str(out / scenario.name / role), *split)  # fmt: skip
        return PlannedRun(scenario=scenario.name, role=role, rag_config=rag, argv=argv, env=env)

    return (
        one("baseline", "apps/rag-demo/configs/rag.gpu.yaml"),
        one("switch", f"{CAUSE_DIR}/{scenario.candidate}"),
    )


def baseline_se(baseline: RunResults, metric: str) -> tuple[float, int]:
    """Standard error of a paired difference, from the baseline alone, and the cluster count.

    The size-weighted spread of the baseline's cluster means (as in ``analyze.py``) times sqrt(2):
    the difference of two runs with uncorrelated cluster errors, an upper bound when the two runs
    of a pair are positively correlated (they share every case).
    """
    sums: dict[str, list[float]] = {}
    for scored in baseline.values:
        for value in scored.values:
            if value.metric == metric and value.status == "ok" and value.value is not None:
                sums.setdefault(scored.case.cluster_id, []).append(value.value)
    return paired_se(sums, metric)


def paired_se(clusters: Mapping[str, Sequence[float]], metric: str = "metric") -> tuple[float, int]:
    """``sqrt(2 * var / k)`` and ``k`` for one run's case values grouped by cluster (D1278).

    ``var = sum_c (n_c / n_bar)^2 (mean_c - case_mean)^2 / (k - 1)``, the size-weighted spread of
    the cluster means around the case mean (D1275); ``sqrt(2)``: the difference of two such runs.

    Raises:
        ScenarioUnderpoweredError: fewer than two clusters.

    Examples:
        Sizes 1, 2, 1 with means 0, 1, 0.5: case mean 0.625, n_bar 4/3, weights 0.5625, 2.25,
        0.5625, var = (0.2197 + 0.3164 + 0.0088) / 2 = 0.27246, se = sqrt(2 * 0.27246 / 3):

        >>> se, k = paired_se({"a": [0.0], "b": [1.0, 1.0], "c": [0.5]})
        >>> round(se, 4), k
        (0.4262, 3)
    """
    k = len(clusters)
    if k < 2:  # a spread needs two clusters
        msg = f"baseline: {k} clusters with an ok {metric} value; the MDE needs at least 2"
        raise ScenarioUnderpoweredError(msg)
    sizes = np.array([len(v) for v in clusters.values()], dtype=float)
    means = np.array([sum(v) / len(v) for v in clusters.values()])
    case_mean = float((sizes * means).sum() / sizes.sum())
    var = float(((sizes / sizes.mean()) ** 2 * (means - case_mean) ** 2).sum() / (k - 1))
    return math.sqrt(2 * var / k), k


def precheck(baseline: RunResults, scenario: Scenario, cfg: PruefstandConfig) -> float | None:
    """The scenario's MDE (m = 1) from the baseline; None for an absolute check.

    Raises:
        ScenarioUnderpoweredError: MDE > the planned drop, or fewer than two clusters.
    """
    if scenario.expected_drop is None:
        return None
    se, _ = baseline_se(baseline, scenario.metric)
    rule = cfg.gate.metrics[scenario.metric]
    delta = rule.max_drop if rule.max_drop is not None else 0.0
    found = minimum_detectable_effect(se, cfg.gate.alpha, delta, m=1)
    if found > scenario.expected_drop:
        msg = f"scenario underpowered: MDE {found:.3f} > expected drop {scenario.expected_drop:.3f}"
        raise ScenarioUnderpoweredError(msg)
    return found


def decide(baseline: RunResults, switch: RunResults, cfg: PruefstandConfig) -> GateReport:
    """The production gate on one scenario pair (directions and seed as in ``pipeline/gate.py``)."""
    rng = np.random.default_rng(cfg.seed)
    return evaluate_gate(
        baseline, switch, cfg.gate, rng, directions=MetricRegistry.full().directions()
    )


def problems(scenario: Scenario, switch: RunResults, report: GateReport) -> list[str]:
    """What is wrong with a scenario's outcome (empty: the expected cause, run state as planned)."""
    found: list[str] = []
    manifest = switch.manifest
    if manifest.infra_error is not None:
        found.append(
            f"infra_error {manifest.infra_error!r}: an infra failure, not a candidate error"
        )
    if scenario.name == "errors":
        checks = [d for d in report.absolute_checks if d.metric == scenario.metric]
        if not checks or all(d.status is GateStatus.PASS for d in checks):
            found.append("error_rate absolute check passed: the closed port made no errors")
    elif not manifest.complete:
        found.append(f"switch run incomplete (stop_reason {manifest.stop_reason})")
    if report.likely_cause != scenario.name:
        found.append(f"likely_cause {report.likely_cause!r}, expected {scenario.name!r}")
    return found


def check_pair(scenario: Scenario, baseline_dir: Path, switch_dir: Path) -> list[str]:
    """Pre-check, gate and judge one recorded scenario pair; return its problems."""
    cfg = load_config(REPO / plan(scenario, Path())[0].argv[3])
    baseline = ArtifactStore(baseline_dir.parent).read_run(baseline_dir).results
    switch = ArtifactStore(switch_dir.parent).read_run(switch_dir).results
    precheck(baseline, scenario, cfg)
    return problems(scenario, switch, decide(baseline, switch, cfg))


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="T6.3 S4 cause-switch scenarios")
    parser.add_argument("--scenarios", nargs="+", default=["all"])
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write-configs", action="store_true")
    action.add_argument("--plan", type=Path, metavar="OUT", help="print the runs (JSON lines)")
    action.add_argument("--check", nargs=2, type=Path, metavar=("BASELINE", "SWITCH"))
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Write the scenario configs, print the run plan, or check one pair (1 on problems)."""
    args = _parser().parse_args(argv)
    try:
        chosen = select(args.scenarios)
        if args.write_configs:
            for path in write_configs():
                print(path.relative_to(REPO))
            return 0
        if args.plan is not None:
            for scenario in chosen:
                for run in plan(scenario, args.plan):
                    print(json.dumps(run.model_dump(mode="json"), ensure_ascii=False))
            return 0
        if len(chosen) != 1:
            print("error: --check takes exactly one scenario", file=sys.stderr)
            return 2
        found = check_pair(chosen[0], *args.check)
    except PruefstandError as err:
        print(f"error: {err}", file=sys.stderr)
        return 1
    for line in found:
        print(f"{chosen[0].name}: {line}", file=sys.stderr)
    print(f"{chosen[0].name}: {'ok' if not found else 'FAILED'}")
    return 1 if found else 0


if __name__ == "__main__":
    raise SystemExit(main())
