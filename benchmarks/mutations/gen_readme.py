"""Generate ``benchmarks/mutations/README.md`` from the ``mutation.yaml`` files (T7.1a S6).

Usage::

    uv run python benchmarks/mutations/gen_readme.py           # write README.md
    uv run python benchmarks/mutations/gen_readme.py --check   # exit 1 when README.md is stale
"""

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # run as a script: import mutations.*

from mutations.schema import MUTATIONS_ROOT, MutationSpec, load_all, load_index

HEADER = """# RQ3 mutation benchmark

Generated by `benchmarks/mutations/gen_readme.py` from the `mutation.yaml` files; do not
edit by hand. Every `patch.diff` applies at `base_sha`; `rag_overrides` merge into
`apps/rag-demo/configs/rag.gpu.yaml` (and the tier-1 `rag.yaml` for `tier1` entries). Apply
one entry on a fresh worktree with
`uv run python benchmarks/mutations/apply.py apply <ID> --worktree <dir>` and undo it with
`revert`. No-ops (`N`) expect PASS and measure the false-alarm rate, never the detection rate.

"""
COLUMNS = (
    "ID",
    "Title",
    "Kind",
    "Change",
    "Tier",
    "Splits",
    "Stratum",
    "tier1",
    "Expected",
    "Metrics",
)


def _row(spec: MutationSpec) -> str:
    expected = spec.expected.status + (" (hard fail)" if spec.expected.hard_fail else "")
    cells = (
        spec.id,
        spec.title,
        spec.kind,
        "patch" if spec.patch else "overrides" if spec.rag_overrides is not None else "data",
        spec.tier,
        ", ".join(spec.splits),
        spec.stratum,
        "yes" if spec.tier1 else "no",
        expected,
        ", ".join(f"`{m}`" for m in spec.expected.metrics) or "–",
    )
    return "| " + " | ".join(cells) + " |"


def render(root: Path = MUTATIONS_ROOT) -> str:
    """Return the README text for the entries listed in ``index.yaml``.

    Raises:
        ConfigError: an entry file is missing or invalid (see ``mutations.schema``).
    """
    index = load_index(root)
    pending = [f"- `{entry}`: {reason}" for entry, reason in sorted(index.pending.items())]
    if pending:
        pending = ["", "## Pending (neither applied nor scored)", "", *pending]
    lines = [
        f"`base_sha`: `{index.base_sha}`",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "| " + " | ".join("---" for _ in COLUMNS) + " |",
        *(_row(spec) for spec in load_all(root)),
        *pending,
    ]
    return HEADER + "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    """Write or check ``README.md``; returns the exit code."""
    parser = argparse.ArgumentParser(description="Generate the mutation benchmark README.")
    parser.add_argument("--check", action="store_true", help="fail when README.md is stale")
    args = parser.parse_args(argv)
    target = MUTATIONS_ROOT / "README.md"
    text = render()
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != text:
            print("benchmarks/mutations/README.md is stale: run gen_readme.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
